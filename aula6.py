# conversão de tipos, coerção
# type convertion, typecasting, coercion
# é o ato de converter um tipo em outro
# tipos imultáveis e primitivos
# str, int, float, bool
print(1 + 1) 
print('A' + 'B') # concatenação

# coerção
print(int('1'), type('1')) # coersão para inteiro
print(float('1'), type('1')) # coersão para float
print(bool(' '))


