# \r\n - Quebrador de linhas -> CRLF
# \n -> LF 
print(12, 34, 56, sep="-", end="\n##")
print(78, 89, sep= '-', end="\n")
print(9, 10, sep="-", end='\n')

"""
Python é uma linguagem de programção de tipagem:
Dinamica / Forte
Strings são textos que estão dentro de aspas
"""
print("Olá Mundo!")

# Aspas simples
print('Meu nome é Jonatas')

# Aspas duplas
print("Eu tenho 33 anos!")

# Escape
print("Jonatas \"Ribeiro Gomes\"")
print('Jonatas "Ribeiro Gomes"')