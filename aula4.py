# Tipos int e float
# int -> Numero inteiro
# O tipo int representa qualque numero positivo ou negativo
# Int sem sinal é considerado positivo
print(11)
print(-11)
print(0)

# float -> Numero com ponto flutuante
# O tipo float representa qualquer numero positivo ou negativo com ponto flutuante
# float sem sinale é considerado positivo

print(3.5)
print(-9.8)
print(0.0)

# A função type mostra o tipo que o Python
# inferiu o valor
print(type(9)) 
print(type('Jonatas'))